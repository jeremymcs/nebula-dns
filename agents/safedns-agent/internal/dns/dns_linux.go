//go:build linux

package dns

import (
	"bufio"
	"fmt"
	"os"
	"os/exec"
	"strings"
)

const resolvConfPath = "/etc/resolv.conf"
const resolvConfBackup = "/etc/resolv.conf.nebuladns.bak"

// Configure sets the system DNS servers
func (m *Manager) Configure(servers []string) error {
	// Check if systemd-resolved is running
	if m.isSystemdResolved() {
		return m.configureSystemdResolved(servers)
	}

	// Fall back to direct resolv.conf modification
	return m.configureResolvConf(servers)
}

func (m *Manager) isSystemdResolved() bool {
	cmd := exec.Command("systemctl", "is-active", "systemd-resolved")
	output, _ := cmd.Output()
	return strings.TrimSpace(string(output)) == "active"
}

func (m *Manager) configureSystemdResolved(servers []string) error {
	// Create a drop-in configuration
	dropInDir := "/etc/systemd/resolved.conf.d"
	if err := os.MkdirAll(dropInDir, 0755); err != nil {
		return err
	}

	content := "[Resolve]\n"
	if len(servers) > 0 {
		content += fmt.Sprintf("DNS=%s\n", strings.Join(servers, " "))
	}

	if err := os.WriteFile(dropInDir+"/nebuladns.conf", []byte(content), 0644); err != nil {
		return err
	}

	// Restart systemd-resolved
	return exec.Command("systemctl", "restart", "systemd-resolved").Run()
}

func (m *Manager) configureResolvConf(servers []string) error {
	// Backup original if not already backed up
	if _, err := os.Stat(resolvConfBackup); os.IsNotExist(err) {
		if err := copyFile(resolvConfPath, resolvConfBackup); err != nil {
			// Ignore if original doesn't exist
			if !os.IsNotExist(err) {
				return err
			}
		}
	}

	// Build new resolv.conf content
	var content strings.Builder
	content.WriteString("# Generated by Nebula DNS Agent\n")
	content.WriteString("# Original configuration backed up to " + resolvConfBackup + "\n\n")

	for _, server := range servers {
		fmt.Fprintf(&content, "nameserver %s\n", server)
	}

	return os.WriteFile(resolvConfPath, []byte(content.String()), 0644)
}

// GetCurrentServers returns the current system DNS servers
func (m *Manager) GetCurrentServers() ([]string, error) {
	file, err := os.Open(resolvConfPath)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	var servers []string
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if strings.HasPrefix(line, "nameserver") {
			parts := strings.Fields(line)
			if len(parts) >= 2 {
				servers = append(servers, parts[1])
			}
		}
	}

	return servers, scanner.Err()
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0644)
}
